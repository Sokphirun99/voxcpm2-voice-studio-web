/**
 * @fileoverview Pure validators and snapshot builders for saved subtitle/TTS projects.
 */

import { ValidationError } from './errors.js';

const PROJECT_KINDS = Object.freeze(['subtitle', 'tts']);
const DEFAULT_PROJECT_PAGE_LIMIT = 50;
const MAX_PROJECT_PAGE_LIMIT = 200;
const PROJECT_ID_PATTERN = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

/**
 * Validates a project id is a non-empty UUID string.
 * @param {unknown} id - Candidate project id.
 * @returns {string} Normalized project id.
 */
export function assertProjectId(id) {
  const normalized = typeof id === 'string' ? id.trim() : '';
  if (!normalized || !PROJECT_ID_PATTERN.test(normalized)) {
    throw new ValidationError('Project id must be a UUID.', 'id', 'INVALID_PROJECT_ID');
  }
  return normalized;
}

/**
 * Validates a project kind.
 * @param {unknown} kind - Candidate project kind.
 * @returns {string} Normalized kind.
 */
export function assertProjectKind(kind) {
  if (!PROJECT_KINDS.includes(kind)) {
    throw new ValidationError("Project kind must be 'subtitle' or 'tts'.", 'kind', 'INVALID_PROJECT_KIND');
  }
  return kind;
}

/**
 * Validates a project title.
 * @param {unknown} title - Candidate project title.
 * @returns {string} Trimmed title.
 */
export function assertProjectTitle(title) {
  const normalized = typeof title === 'string' ? title.trim() : '';
  if (!normalized) {
    throw new ValidationError('Project title is required.', 'title', 'INVALID_PROJECT_TITLE');
  }
  return normalized;
}

/**
 * Validates a project payload is a non-null, non-array object.
 * @param {unknown} payload - Candidate project payload.
 * @returns {object} The payload.
 */
export function assertProjectPayload(payload) {
  if (payload === null || typeof payload !== 'object' || Array.isArray(payload)) {
    throw new ValidationError('Project payload must be a JSON object.', 'payload', 'INVALID_PROJECT_PAYLOAD');
  }
  return payload;
}

/**
 * Normalizes and validates a stored project record.
 * @param {unknown} raw - Raw project record.
 * @returns {{ id: string, kind: string, title: string, payload: object, createdAt: string, updatedAt: string, deletedAt: string|null }} Normalized record.
 */
export function normalizeProjectRecord(raw) {
  if (!raw || typeof raw !== 'object' || Array.isArray(raw)) {
    throw new ValidationError('Project record must be an object.', 'project', 'INVALID_PROJECT_RECORD');
  }
  return {
    id: assertProjectId(raw.id),
    kind: assertProjectKind(raw.kind),
    title: assertProjectTitle(raw.title),
    payload: assertProjectPayload(raw.payload),
    createdAt: typeof raw.createdAt === 'string' && raw.createdAt ? raw.createdAt : new Date().toISOString(),
    updatedAt: typeof raw.updatedAt === 'string' && raw.updatedAt ? raw.updatedAt : new Date().toISOString(),
    deletedAt: typeof raw.deletedAt === 'string' ? raw.deletedAt : null,
  };
}

/**
 * Returns true when a project record is not soft-deleted.
 * @param {object|null|undefined} record - Project record.
 * @returns {boolean} True when active.
 */
export function isProjectActive(record) {
  return Boolean(record && !record.deletedAt);
}

/**
 * Builds a project summary (id, kind, title, timestamps) without the full payload.
 * @param {object} record - Project record.
 * @returns {{ id: string, kind: string, title: string, createdAt: string, updatedAt: string }} Public summary.
 */
export function toProjectSummary(record) {
  return {
    id: record.id,
    kind: record.kind,
    title: record.title,
    createdAt: record.createdAt,
    updatedAt: record.updatedAt,
  };
}

/**
 * Builds a subtitle project snapshot. Stores video filename metadata, segments, translations,
 * speaker names, and subtitle options — never raw video blobs — so the video can be re-linked
 * later for MP4 burn-in.
 * @param {object} spec - Snapshot fields.
 * @param {string} [spec.id] - Project id (generated by storage on create).
 * @param {string} spec.title - Project title.
 * @param {string|null} [spec.videoFileName] - Original video/audio file name for re-linking.
 * @param {Array<object>} [spec.segments] - Editable subtitle segments.
 * @param {object<string,string>} [spec.speakerNames] - Speaker id -> display name map.
 * @param {object} [spec.subtitleOptions] - Subtitle extraction/display options.
 * @param {string} [spec.detectedLanguage] - Detected source language.
 * @param {string} [spec.translatedLanguage] - Active target language.
 * @param {boolean} [spec.hasTranslation] - Whether translated text exists.
 * @param {string} [spec.createdAt] - Creation timestamp.
 * @param {string} [spec.updatedAt] - Update timestamp.
 * @returns {{ id, kind, title, payload, createdAt, updatedAt, deletedAt }} Subtitle project snapshot.
 */
export function createSubtitleProjectSnapshot({
  id,
  title,
  videoFileName = null,
  segments = [],
  speakerNames = {},
  subtitleOptions = {},
  detectedLanguage = '',
  translatedLanguage = '',
  hasTranslation = false,
  createdAt,
  updatedAt,
} = {}) {
  const now = new Date().toISOString();
  return {
    id: id || '',
    kind: 'subtitle',
    title: assertProjectTitle(title),
    payload: {
      videoFileName: typeof videoFileName === 'string' && videoFileName ? videoFileName : null,
      segments: Array.isArray(segments) ? segments : [],
      speakerNames: typeof speakerNames === 'object' && !Array.isArray(speakerNames) ? speakerNames : {},
      subtitleOptions: typeof subtitleOptions === 'object' && !Array.isArray(subtitleOptions) ? subtitleOptions : {},
      detectedLanguage: typeof detectedLanguage === 'string' ? detectedLanguage : '',
      translatedLanguage: typeof translatedLanguage === 'string' ? translatedLanguage : '',
      hasTranslation: Boolean(hasTranslation),
    },
    createdAt: createdAt || now,
    updatedAt: updatedAt || now,
    deletedAt: null,
  };
}

/**
 * Builds a TTS project snapshot storing script text, voice id, and synthesis options.
 * @param {object} spec - Snapshot fields.
 * @param {string} [spec.id] - Project id (generated by storage on create).
 * @param {string} spec.title - Project title.
 * @param {string} [spec.script] - TTS script text.
 * @param {string} [spec.voiceId] - Selected voice id.
 * @param {object} [spec.ttsOptions] - TTS synthesis options.
 * @param {string} [spec.createdAt] - Creation timestamp.
 * @param {string} [spec.updatedAt] - Update timestamp.
 * @returns {{ id, kind, title, payload, createdAt, updatedAt, deletedAt }} TTS project snapshot.
 */
export function createTtsProjectSnapshot({
  id,
  title,
  script = '',
  voiceId = '',
  ttsOptions = {},
  createdAt,
  updatedAt,
} = {}) {
  const now = new Date().toISOString();
  return {
    id: id || '',
    kind: 'tts',
    title: assertProjectTitle(title),
    payload: {
      script: typeof script === 'string' ? script : '',
      voiceId: typeof voiceId === 'string' ? voiceId : '',
      ttsOptions: typeof ttsOptions === 'object' && !Array.isArray(ttsOptions) ? ttsOptions : {},
    },
    createdAt: createdAt || now,
    updatedAt: updatedAt || now,
    deletedAt: null,
  };
}

export { DEFAULT_PROJECT_PAGE_LIMIT, MAX_PROJECT_PAGE_LIMIT };
